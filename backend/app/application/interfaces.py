"""Repository interfaces (protocols) for Family Financial OS.

Defines the contracts that infrastructure implementations must follow.
The application layer depends on these abstractions, not on SQLite.
"""

from __future__ import annotations
from typing import List, Optional, Dict, Any
from decimal import Decimal

from app.domain.domain import (
    Money, Timestamp, Account, AccountType, Transaction,
    TransactionType, TransactionStatus, Budget, Debt, Goal,
    Asset, Liability, Member, Household, User, Notification,
    LedgerEntry, RecurringPayment, DebtPayment, GoalContribution,
    Transfer, Session
)


class HouseholdRepository:
    def create(self, household: Household) -> Household: ...
    def get_by_id(self, id: str) -> Optional[Household]: ...
    def get_all(self) -> List[Household]: ...
    def update(self, household: Household) -> Household: ...
    def delete(self, id: str) -> None: ...


class MemberRepository:
    def create(self, member: Member) -> Member: ...
