    def get_by_household(self, household_id: str) -> List[Account]: ...
    def get_balance(self, account_id: str) -> Optional[Money]: ...
    def update_balance(self, id: str, balance: Money) -> None: ...
    def delete(self, id: str, household_id: str) -> None: ...


